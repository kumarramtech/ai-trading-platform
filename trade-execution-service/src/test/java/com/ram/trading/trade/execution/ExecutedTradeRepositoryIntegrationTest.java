    @Test
    void targetExtensionMustPersistOnceAndBeIdempotentForTheSameTarget() {
        saveOpenTrade(1010L, "BUY", 5, "100.00");
        jdbcTemplate.update("UPDATE executed_trades SET target_price = ? WHERE signal_id = ?",
                new BigDecimal("110.00"), 1010L);

        ExecutedTradeRecord extended = repository.updateProtectionLevels(
                1010L, null, new BigDecimal("112.50"), true);
        assertEquals(Boolean.TRUE, extended.getTargetExtended());
        assertMoney("112.50000000", extended.getTargetPrice());

        ExecutedTradeRecord repeated = repository.updateProtectionLevels(
                1010L, null, new BigDecimal("112.50"), true);
        assertEquals(Boolean.TRUE, repeated.getTargetExtended());
        assertMoney("112.50000000", repeated.getTargetPrice());

        assertThrows(IllegalStateException.class, () -> repository.updateProtectionLevels(
                1010L, null, new BigDecimal("115.00"), true));
    }

